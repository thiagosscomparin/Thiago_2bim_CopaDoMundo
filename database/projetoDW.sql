DROP TABLE IF EXISTS selecao, partida;

CREATE TABLE selecao (
    id_selecao SERIAL PRIMARY KEY,
    nome_selecao VARCHAR(50) NOT NULL,
    grupo CHAR(1) NOT NULL,
    bandeira_url VARCHAR(255)
);

CREATE TABLE partida (
    id_partida SERIAL PRIMARY KEY,
    selecao_casa_id INTEGER NOT NULL REFERENCES selecao(id_selecao),
    selecao_fora_id INTEGER NOT NULL REFERENCES selecao(id_selecao),
    gols_casa INTEGER,
    gols_fora INTEGER,
    data_partida DATE,
    estadio VARCHAR(100)
);

